n=int(input("Здравствуйте. введите число от 1 до 25: "))
d=0
if n>= 1 and n<=25:
    for i in range(2,n):
        if n % i ==0: # проверяем делится ли n без остатка на числа которые стоят перед ним начиная с 2
            d+=1
    if n>=2 and d==0:
        print(n,"- Y")
    else:
        print(n,"- N")
else:
    print("Не работает")       