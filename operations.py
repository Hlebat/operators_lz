n = int(input("Здравсвуйте. Введите число от 1 до 100000: "))
d= 0
if n >= 1 and n <= 100000: # смотрим, входит ли введенное число в диапозон
    while n > 0: # Пока число больше 0, отнимаем 3 и считаем сколько раз отняли
        n = n - 3
        d+= 1
    print(d)
else:
    print("число не входит в диапозон")