n = int(input("Здравствутйе. Введите число от 1 до 100000: "))
if n >= 1 and n <= 100000:
    if n % 3 == 0:
        # Если делится без остатка делим
        d = n // 3
    else:
        # Если есть остаток добавляем ещё одну операцию
        d = n // 3 + 1
    #результат
    print(d)
else:
    print("число не подходит")